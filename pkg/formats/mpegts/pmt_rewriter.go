package mpegts

import (
	"io"
)

// pmtRewriter is an io.Writer that is placed between astits.Muxer and the output.
// astits.Muxer is not able to write program descriptors nor descriptors that it doesn't
// know, therefore the PMT it generates is replaced with one that
// contains the program descriptors and the descriptors of each stream
// verbatim. Every other packet is forwarded untouched.
type pmtRewriter struct {
	W io.Writer

	// descriptor loop of the program.
	programDescs []byte

	// descriptor loops that replace the ones of the PMT, by PID.
	streamDescs map[uint16][]byte

	buf    []byte
	pmtCC  uint8
	pmtAsm sectionAssembler
}

func (r *pmtRewriter) Write(p []byte) (int, error) {
	n := len(p)

	r.buf = append(r.buf, p...)

	var out []byte

	for len(r.buf) >= packetSize {
		pkt := r.buf[:packetSize]

		if pkt[0] == syncByte && (uint16(pkt[1]&0x1F)<<8|uint16(pkt[2])) == writerPMTPID {
			for _, sec := range r.pmtAsm.push(pkt) {
				rewritten, err := r.rewrite(sec)
				if err != nil {
					return 0, err
				}

				var pkts []byte
				pkts, r.pmtCC = packetizeSection(writerPMTPID, r.pmtCC, rewritten)
				out = append(out, pkts...)
			}
		} else {
			out = append(out, pkt...)
		}

		r.buf = r.buf[packetSize:]
	}

	// move remaining bytes at the beginning
	r.buf = append(r.buf[:0], r.buf...)

	if len(out) != 0 {
		_, err := r.W.Write(out)
		if err != nil {
			return 0, err
		}
	}

	return n, nil
}

func (r *pmtRewriter) rewrite(sec []byte) ([]byte, error) {
	var pmt rawPMT
	err := pmt.unmarshal(sec)
	if err != nil {
		// not generated by us, forward it as it is
		return sec, nil //nolint:nilerr
	}

	pmt.ProgramInfo = r.programDescs

	for i := range pmt.Streams {
		if descs, ok := r.streamDescs[pmt.Streams[i].PID]; ok {
			pmt.Streams[i].Descriptors = descs
		}
	}

	return pmt.marshal()
}
